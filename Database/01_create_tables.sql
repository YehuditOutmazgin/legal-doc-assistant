DROP TABLE REFRESH_TOKENS CASCADE CONSTRAINTS PURGE;
DROP TABLE AUDIT_LOGS CASCADE CONSTRAINTS PURGE;
DROP TABLE CONTRACTS CASCADE CONSTRAINTS PURGE;
DROP TABLE TEMPLATES CASCADE CONSTRAINTS PURGE;
DROP TABLE CLIENTS CASCADE CONSTRAINTS PURGE;
DROP TABLE USERS CASCADE CONSTRAINTS PURGE;

-- ============================================
-- Table: USERS
-- ============================================
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR2(255) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(500) NOT NULL,
    FIRST_NAME VARCHAR2(100) NOT NULL,
    LAST_NAME VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(20) NOT NULL CHECK (ROLE IN ('ADMIN', 'LAWYER', 'CLERK')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0, 1))
);

-- ============================================
-- Table: REFRESH_TOKENS (for production use)
-- ============================================
CREATE TABLE REFRESH_TOKENS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    TOKEN VARCHAR2(255) NOT NULL UNIQUE,
    EXPIRES_AT TIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    IS_REVOKED NUMBER(1) DEFAULT 0 NOT NULL CHECK (IS_REVOKED IN (0, 1)),
    CONSTRAINT FK_REFRESH_TOKENS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

-- ============================================
-- Table: CLIENTS
-- ============================================
CREATE TABLE CLIENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255) NOT NULL,
    TYPE VARCHAR2(20) NOT NULL CHECK (TYPE IN ('INDIVIDUAL', 'COMPANY')),
    EMAIL VARCHAR2(255) NOT NULL,
    PHONE VARCHAR2(50) NOT NULL,
    ADDRESS VARCHAR2(500) NOT NULL,
    COMPANY_REGISTRATION_NUMBER VARCHAR2(50),
    CONTACT_PERSON_NAME VARCHAR2(255),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0, 1))
);

-- ============================================
-- Table: TEMPLATES
-- ============================================
CREATE TABLE TEMPLATES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255) NOT NULL,
    DESCRIPTION VARCHAR2(1000) NOT NULL,
    CONTENT CLOB NOT NULL,
    CATEGORY VARCHAR2(100) NOT NULL,
    CREATED_BY_USER_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT FK_TEMPLATES_USER FOREIGN KEY (CREATED_BY_USER_ID) REFERENCES USERS(ID)
);

-- ============================================
-- Table: CONTRACTS
-- ============================================
CREATE TABLE CONTRACTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(500) NOT NULL,
    CONTENT CLOB NOT NULL,
    STATUS VARCHAR2(20) NOT NULL CHECK (STATUS IN ('DRAFT', 'REVIEW', 'SIGNED', 'ARCHIVED')),
    CLIENT_ID NUMBER NOT NULL,
    TEMPLATE_ID NUMBER,
    CREATED_BY_USER_ID NUMBER NOT NULL,
    ASSIGNED_TO_USER_ID NUMBER,
    S3_KEY VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP,
    SIGNED_AT TIMESTAMP,
    SIGNED_BY_NAME VARCHAR2(255),
    NOTES VARCHAR2(2000),
    CONSTRAINT FK_CONTRACTS_CLIENT FOREIGN KEY (CLIENT_ID) REFERENCES CLIENTS(ID),
    CONSTRAINT FK_CONTRACTS_TEMPLATE FOREIGN KEY (TEMPLATE_ID) REFERENCES TEMPLATES(ID),
    CONSTRAINT FK_CONTRACTS_CREATED_BY FOREIGN KEY (CREATED_BY_USER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_CONTRACTS_ASSIGNED_TO FOREIGN KEY (ASSIGNED_TO_USER_ID) REFERENCES USERS(ID)
);

-- ============================================
-- Table: AUDIT_LOGS
-- ============================================
CREATE TABLE AUDIT_LOGS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTRACT_ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    ACTION VARCHAR2(100) NOT NULL,
    DETAILS VARCHAR2(2000),
    TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_AUDIT_CONTRACT FOREIGN KEY (CONTRACT_ID) REFERENCES CONTRACTS(ID),
    CONSTRAINT FK_AUDIT_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

COMMIT;
