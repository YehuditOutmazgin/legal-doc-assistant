-- CLIENTS indexes
CREATE INDEX IDX_CLIENTS_EMAIL ON CLIENTS(EMAIL);
CREATE INDEX IDX_CLIENTS_TYPE ON CLIENTS(TYPE);
CREATE INDEX IDX_CLIENTS_IS_ACTIVE ON CLIENTS(IS_ACTIVE);

-- TEMPLATES indexes
CREATE INDEX IDX_TEMPLATES_CATEGORY ON TEMPLATES(CATEGORY);
CREATE INDEX IDX_TEMPLATES_CREATED_BY ON TEMPLATES(CREATED_BY_USER_ID);
CREATE INDEX IDX_TEMPLATES_IS_ACTIVE ON TEMPLATES(IS_ACTIVE);

-- CONTRACTS indexes
CREATE INDEX IDX_CONTRACTS_STATUS ON CONTRACTS(STATUS);
CREATE INDEX IDX_CONTRACTS_CLIENT_ID ON CONTRACTS(CLIENT_ID);
CREATE INDEX IDX_CONTRACTS_TEMPLATE_ID ON CONTRACTS(TEMPLATE_ID);
CREATE INDEX IDX_CONTRACTS_CREATED_BY ON CONTRACTS(CREATED_BY_USER_ID);
CREATE INDEX IDX_CONTRACTS_ASSIGNED_TO ON CONTRACTS(ASSIGNED_TO_USER_ID);
CREATE INDEX IDX_CONTRACTS_CREATED_AT ON CONTRACTS(CREATED_AT);

-- AUDIT_LOGS indexes
